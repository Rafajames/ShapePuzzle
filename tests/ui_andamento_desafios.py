# Relógio sem saltos, fase em andamento, desafio da semana e contra o relógio.
import os, sys, json
RAIZ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SAIDA = os.path.join(RAIZ, 'tests', 'saida') + os.sep
os.makedirs(SAIDA, exist_ok=True)
from playwright.sync_api import sync_playwright
URL = 'http://127.0.0.1:8765/index.html'
falhas = []; erros = []
def check(c, m):
    print(('  ok   ' if c else '  FALHA ') + m)
    if not c: falhas.append(m)
COLOCA = "(()=>{const r=dicaDe(S.jogo); if(r.tipo!=='ok') return false; r.peca.formato=r.o; return tentarColocar(r.peca,r.px,r.py);})()"
FIM = "try{localStorage.setItem('shapepuzzle.tuto','{\"sel\":true,\"giro\":true,\"esp\":true,\"fim\":true}')}catch(e){}"
ABRE = "document.querySelectorAll('#ov-menu details.sec').forEach(d=>d.open=true)"
def fecha(pg): pg.evaluate("document.querySelectorAll('.ov.on').forEach(o=>o.classList.remove('on'))"); pg.wait_for_timeout(100)
def novo(b, locale='pt-BR', w=390, h=844, ctx=None):
    ctx = ctx or b.new_context(locale=locale, viewport={'width': w, 'height': h}, has_touch=True, is_mobile=True)
    if not getattr(ctx, '_ini', False): ctx.add_init_script(FIM); ctx._ini = True
    pg = ctx.new_page(); pg.on('pageerror', lambda e: erros.append(str(e)))
    pg.goto(URL); pg.wait_for_selector('#btnJogar'); pg.wait_for_timeout(300)
    return ctx, pg
def jogar(pg): pg.click('#btnJogar'); pg.wait_for_timeout(300)
def vencer(pg, espera=True):
    n = 0
    while not pg.evaluate("S.venceu") and n < 80: pg.evaluate(COLOCA); n += 1
    if espera: pg.wait_for_selector('#ov-win.on', timeout=9000); pg.wait_for_timeout(250)
def estado(pg): return pg.evaluate("JSON.stringify({c: S.cur.k + ':' + (S.cur.i ?? S.cur.data ?? S.cur.semana ?? ''), g: S.jogo.grade.map(l => l.map(id => id ? S.jogo.mapa.get(id).ord : 0)), r: S.jogo.reserva.map(p => [p.ord, p.formato]), j: S.jog, d: S.dicas, h: S.hist.length, sel: S.sel && S.sel.ord})")

with sync_playwright() as pw:
    b = pw.chromium.launch()
    ctx, pg = novo(b); jogar(pg)

    print('Relógio: tela bloqueada não conta')
    pg.evaluate("carregar({k:'b',i:0})"); pg.wait_for_timeout(200)
    pg.evaluate(COLOCA); pg.wait_for_timeout(700)
    a0 = pg.evaluate("S.t.acum"); e0 = pg.evaluate("Est.tempo")
    check(a0 > 300, f'o relógio corre enquanto joga ({a0:.0f} ms)')
    pg.evaluate("S.t.ult = performance.now() - 120000"); pg.wait_for_timeout(600)
    a1 = pg.evaluate("S.t.acum"); e1 = pg.evaluate("Est.tempo")
    check(a1 - a0 < 1500, f'2 minutos de tela congelada não entram no tempo da fase (+{a1 - a0:.0f} ms)')
    check(e1 - e0 < 1500, f'nem nas estatísticas (+{e1 - e0:.0f} ms)')
    pg.evaluate("S.cur.k === 'b' && Object.defineProperty(document, 'hidden', {value: true, configurable: true}); document.dispatchEvent(new Event('visibilitychange'))")
    pg.wait_for_timeout(1200)
    a2 = pg.evaluate("S.t.acum")
    pg.evaluate("Object.defineProperty(document, 'hidden', {value: false, configurable: true}); document.dispatchEvent(new Event('visibilitychange'))"); pg.wait_for_timeout(500)
    a3 = pg.evaluate("S.t.acum")
    check(abs(a2 - a1) < 700, f'com a aba escondida o tempo para ({a2 - a1:.0f} ms)')
    check(a3 - a2 < 1000, f'ao voltar não aparece um salto ({a3 - a2:.0f} ms)')

    print('Fase em andamento: guardar e continuar')
    pg.evaluate("carregar({k:'b',i:2})"); pg.wait_for_timeout(200)
    check(pg.evaluate("localStorage.getItem('shapepuzzle.andamento')") in (None, 'null'), 'fase sem nenhuma peça não guarda nada')
    for _ in range(3): pg.evaluate(COLOCA)
    pg.evaluate("S.sel && (S.sel.formato = girar(S.sel.formato))"); pg.evaluate("renderReserva()")
    pg.evaluate("acaoDesfazer()"); pg.evaluate(COLOCA)
    pg.wait_for_timeout(700)
    antes = estado(pg); acum = pg.evaluate("S.t.acum")
    sv = pg.evaluate("JSON.parse(localStorage.getItem('shapepuzzle.andamento'))")
    check(sv and sv['v'] == 1 and len(sv['pos']) == 3 and sv['cur']['i'] == 2, 'as 3 peças postas foram guardadas')
    check(abs(sv['acum'] - acum) < 2000, f"tempo guardado ({sv['acum']} ms)")
    acum_antes = pg.evaluate("S.t.acum")
    pg.reload(); pg.wait_for_selector('#btnJogar'); pg.wait_for_timeout(500)
    check(pg.is_visible('#splashMsg') and 'andamento' in pg.inner_text('#splashMsg'), 'a tela inicial avisa que a fase foi guardada')
    check(estado(pg) == antes, 'peças, ordem, giros, jogadas e dicas voltaram iguais')
    check(abs(pg.evaluate("S.t.acum") - acum_antes) < 150, f"o tempo continua de onde parou ({pg.evaluate('S.t.acum'):.0f} ms)")
    jogar(pg)
    pg.evaluate(COLOCA); pg.wait_for_timeout(300)
    check(pg.evaluate("S.jogo.mapa.size") == 4 and pg.evaluate("S.jog") == sv['jog'] + 1, 'dá para continuar jogando a partir dali')
    check(pg.evaluate("acaoDesfazer(), S.jogo.mapa.size") == 3, 'o desfazer funciona nas peças restauradas')
    pg.screenshot(path=SAIDA + 'andamento.png')
    vencer(pg); fecha(pg); pg.wait_for_timeout(600)
    check(pg.evaluate("localStorage.getItem('shapepuzzle.andamento')") in (None, 'null'), 'ao vencer, o andamento é apagado')
    pg.reload(); pg.wait_for_selector('#btnJogar'); pg.wait_for_timeout(400)
    check(pg.is_hidden('#splashMsg') or 'andamento' not in pg.inner_text('#splashMsg'), 'depois de vencer abre sem aviso de fase guardada')
    jogar(pg)

    print('Fase em andamento: fila, tamanhos e dados estragados')
    pg.evaluate("carregar({k:'b',i:44})"); pg.wait_for_timeout(300)
    for _ in range(4): pg.evaluate(COLOCA)
    pg.wait_for_timeout(600); antes = estado(pg)
    n = pg.evaluate("S.n"); fila = pg.evaluate("S.jogo.fila")
    pg.reload(); pg.wait_for_selector('#btnJogar'); pg.wait_for_timeout(500)
    check(estado(pg) == antes and pg.evaluate("S.n") == n and pg.evaluate("S.jogo.fila") == fila, f'fase {n}×{n} com fila de {fila} volta igual')
    jogar(pg)
    sv = pg.evaluate("JSON.parse(localStorage.getItem('shapepuzzle.andamento'))")
    ruim = dict(sv); ruim['h'] = '00000000'
    pg.evaluate("v => { restaurando = true; localStorage.setItem('shapepuzzle.andamento', JSON.stringify(v)); }", ruim); pg.reload(); pg.wait_for_selector('#btnJogar'); pg.wait_for_timeout(400)
    check(pg.evaluate("S.jogo.mapa.size") == 0 and pg.evaluate("S.cur.i") == pg.evaluate("Math.min(prog.max, BUILTIN.length - 1)"), 'se a fase mudou, a fase guardada é ignorada')
    ruim = json.loads(json.dumps(sv)); ruim['pos'][0]['x'] = 40
    pg.evaluate("v => { restaurando = true; localStorage.setItem('shapepuzzle.andamento', JSON.stringify(v)); }", ruim); pg.reload(); pg.wait_for_selector('#btnJogar'); pg.wait_for_timeout(400)
    check(pg.evaluate("S.jogo.mapa.size") == 0 and pg.evaluate("S.jog") == 0, 'peça fora do tabuleiro: recomeça a fase sem travar')
    pg.evaluate("restaurando = true; localStorage.setItem('shapepuzzle.andamento', '{lixo')"); pg.reload(); pg.wait_for_selector('#btnJogar'); pg.wait_for_timeout(400)
    check(pg.evaluate("S.jogo.mapa.size") == 0, 'texto corrompido é ignorado')
    jogar(pg)

    print('Desafio da semana')
    fecha(pg); pg.click('#btnMenu'); pg.evaluate(ABRE); pg.wait_for_timeout(300)
    check('Semana' in pg.inner_text('#semSub') and pg.inner_text('#semTag') == 'Jogar', 'atalho do menu mostra a semana')
    pg.click('#btnSem'); pg.wait_for_function("S.cur && S.cur.k === 's'", timeout=25000); pg.wait_for_timeout(400)
    ch = pg.evaluate("S.cur.semana"); texto = pg.evaluate("S.cur.text")
    check(ch == pg.evaluate("semanaDe(dataHoje())"), f'a fase é da semana {ch}')
    check(pg.inner_text('#titulo .t1') == 'Semana 45' and pg.inner_text('#titulo .t2') == 'desafio da semana' and pg.evaluate("S.n") == 6 and pg.evaluate("S.jogo.fila") == 5, 'tabuleiro 6×6, 5 peças por vez (mínimo padrão)')
    check(pg.evaluate("document.querySelector('#btnDica').disabled") is False, 'dicas continuam valendo no desafio da semana')
    check(pg.evaluate("JSON.parse(localStorage.getItem('shapepuzzle.semfase')).text") == texto, 'a fase da semana fica guardada no aparelho')
    pg.screenshot(path=SAIDA + 'semana.png')
    vencer(pg)
    check('semana' in pg.inner_text('#winTitulo').lower(), 'título da vitória: ' + pg.inner_text('#winTitulo'))
    check(pg.evaluate("sem[S.cur.semana].t") > 0 and pg.evaluate("recs['s:' + S.cur.semana].t") > 0, 'tempo da semana e recorde guardados')
    pg.click('#winActs .btn:has-text("Compartilhar resultado")'); pg.wait_for_timeout(300)
    check('Desafio da semana' in pg.evaluate("document.querySelector('#shTxt') ? document.querySelector('#shTxt').value || document.querySelector('#shTxt').textContent : document.body.innerText"), 'o texto de compartilhar menciona o desafio')
    fecha(pg); pg.click('#btnMenu'); pg.evaluate(ABRE); pg.wait_for_timeout(300)
    check(pg.inner_text('#semTag').startswith('✓'), 'o menu mostra a semana concluída: ' + pg.inner_text('#semTag'))
    pg.evaluate("sem['2026-W01'] = {t: 5000, j: 5, d: 0}; const m = semanaIdx(dataHoje()); for (let i = 1; i <= 2; i++){ const d = new Date(); d.setDate(d.getDate() - 7 * i); sem[semanaDe(fmtData(d))] = {t: 6000, j: 6, d: 0}; } store.set('sem', sem)")
    pg.evaluate("renderDiario()")
    check('🔥 3' in pg.inner_text('#semSub'), 'três semanas seguidas aparecem no menu: ' + pg.inner_text('#semSub'))
    pg.evaluate("abrirEstatisticas()"); pg.wait_for_timeout(300)
    tx = pg.inner_text('#estCorpo').lower()
    check('desafio da semana' in tx and 'semanas jogadas' in tx and 'contra o relógio' in tx, 'estatísticas ganharam as seções novas')
    fecha(pg)
    pg.evaluate("localStorage.removeItem('shapepuzzle.semfase')")
    ctx2, p2 = novo(b); jogar(p2)
    p2.click('#btnMenu'); p2.evaluate(ABRE); p2.click('#btnSem'); p2.wait_for_function("S.cur && S.cur.k === 's'", timeout=25000)
    check(p2.evaluate("S.cur.text") == texto, 'em outro aparelho a fase da semana é a mesma')
    ctx2.close()

    print('Contra o relógio')
    pg.evaluate("carregar({k:'b',i:0})"); pg.wait_for_timeout(300)
    for _ in range(2): pg.evaluate(COLOCA)
    pg.wait_for_timeout(500); sv0 = pg.evaluate("localStorage.getItem('shapepuzzle.andamento')")
    pg.click('#btnMenu'); pg.evaluate(ABRE); pg.wait_for_timeout(200)
    check('Quantas fases' in pg.inner_text('#corrSub'), 'atalho explica o desafio')
    pg.click('#btnCorr'); pg.wait_for_function("S.cur && S.cur.k === 'r'", timeout=15000); pg.wait_for_timeout(500)
    check(pg.inner_text('#titulo .t1') == 'Corrida' and pg.evaluate("Corrida.ativa"), 'a corrida começou')
    check(pg.inner_text('#stTempo') in ('3:00', '2:59'), 'contagem regressiva a partir de 3:00: ' + pg.inner_text('#stTempo'))
    check(pg.evaluate("document.querySelector('#btnDica').disabled") is True, 'dicas desligadas na corrida')
    pg.evaluate("acaoDica()"); pg.wait_for_timeout(100)
    check('Dicas ficam desligadas' in pg.inner_text('#toast'), 'aviso ao tentar usar dica')
    pg.wait_for_timeout(1300)
    check(pg.inner_text('#stTempo') in ('2:58', '2:57', '2:59'), 'o relógio anda: ' + pg.inner_text('#stTempo'))
    pg.screenshot(path=SAIDA + 'corrida.png')
    vencer(pg, False); pg.wait_for_function("S.cur.k === 'r' && S.cur.n === 1 && !S.venceu", timeout=15000)
    check(pg.evaluate("Corrida.feitas") == 1 and '1 feita' in pg.inner_text('#titulo .t2'), 'resolver uma fase leva direto para a próxima: ' + pg.inner_text('#titulo .t2'))
    check(pg.evaluate("localStorage.getItem('shapepuzzle.andamento')") == sv0, 'a corrida não apaga a fase em andamento guardada')
    check(pg.evaluate("!document.querySelector('#ov-win.on')"), 'nenhuma tela de vitória no meio da corrida')
    pg.evaluate("Corrida.fim = Date.now() + 1500"); pg.wait_for_timeout(800)
    check(pg.evaluate("S.t.ativo || true") and pg.inner_text('#stTempo') in ('0:02', '0:01', '0:00') and pg.evaluate("document.querySelector('#stTempo').classList.contains('urg')"), 'nos últimos segundos o contador fica em alerta')
    pg.wait_for_selector('#ov-win.on', timeout=8000); pg.wait_for_timeout(300)
    check(pg.inner_text('#winTitulo') == 'Tempo esgotado!' and '1 fase' in pg.inner_text('#winTexto'), 'fim da corrida: ' + pg.inner_text('#winTexto'))
    check('Novo recorde' in pg.inner_text('#winBadge') and pg.evaluate("corr.melhor") == 1 and pg.evaluate("corr.jogos") == 1, 'primeira corrida vira recorde')
    check(pg.evaluate("S.venceu") is True and pg.evaluate("document.querySelector('#btnDica').disabled"), 'o tabuleiro trava no fim')
    pg.screenshot(path=SAIDA + 'corrida-fim.png')
    pg.click('#winActs .btn:has-text("Jogar de novo")'); pg.wait_for_function("S.cur && S.cur.k === 'r' && S.cur.n === 0 && Corrida.ativa", timeout=15000)
    check(pg.evaluate("Corrida.feitas") == 0, 'jogar de novo recomeça do zero')
    pg.evaluate("Corrida.fim = Date.now() + 700"); pg.wait_for_selector('#ov-win.on', timeout=8000)
    check('Seu recorde: 1' in pg.inner_text('#winBadge') and pg.evaluate("corr.jogos") == 2 and pg.evaluate("corr.melhor") == 1, 'sem bater o recorde: ' + pg.inner_text('#winBadge'))
    pg.click('#winActs .btn:has-text("Menu")'); pg.wait_for_timeout(300)
    check(pg.is_visible('#ov-menu') and 'Recorde: 1 fase' in pg.inner_text('#corrSub'), 'menu mostra o recorde: ' + pg.inner_text('#corrSub'))
    print('Contra o relógio: abandonar')
    pg.evaluate(ABRE); pg.click('#btnCorr'); pg.wait_for_function("S.cur && S.cur.k === 'r' && Corrida.ativa", timeout=15000)
    pg.evaluate("carregar({k:'b',i:1})"); pg.evaluate("Corrida.fim = Date.now() - 1000"); pg.wait_for_timeout(1000)
    check(pg.evaluate("Corrida.ativa") is False and pg.evaluate("corr.jogos") == 2 and pg.evaluate("!document.querySelector('#ov-win.on')"), 'escolher outra fase abandona a corrida sem contar')
    check(pg.evaluate("S.cur.k") == 'b' and not pg.evaluate("document.querySelector('#stTempo').classList.contains('urg')"), 'a fase normal volta ao relógio normal')

    print('Backup leva as semanas e a corrida')
    d = pg.evaluate("dadosLimpos()")
    check(len(d.get('sem', {})) >= 3 and d.get('corr', {}).get('melhor') == 1, 'o backup inclui semanas e corrida')

    print('Inglês')
    pg.evaluate("lang = 'en'; store.set('lang', 'en'); aplicarIdioma(); abrirMenu()"); pg.evaluate(ABRE); pg.wait_for_timeout(300)
    txt = pg.inner_text('#ov-menu')
    check('Weekly challenge' in txt and 'Against the clock' in txt and 'Week ' in txt, 'atalhos em inglês')
    pg.click('#btnCorr'); pg.wait_for_function("S.cur && S.cur.k === 'r'", timeout=15000)
    check(pg.inner_text('#titulo .t1') == 'Race', 'título da corrida em inglês')
    pg.evaluate("Corrida.feitas = 3; Corrida.fim = Date.now() + 500"); pg.wait_for_selector('#ov-win.on', timeout=8000); pg.wait_for_timeout(300)
    check(pg.inner_text('#winTitulo') == "Time's up!" and '3 levels' in pg.inner_text('#winTexto'), 'fim da corrida em inglês: ' + pg.inner_text('#winTexto'))
    b.close()
print('erros de página:', erros)
if erros: falhas.append('erros de página')
print('TUDO OK' if not falhas else 'FALHAS: ' + str(falhas)); sys.exit(1 if falhas else 0)
