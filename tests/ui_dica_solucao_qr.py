# Dica em degraus (peça → lugar → oferta da solução), solução animada e QR code do compartilhar.
import os, sys, re
RAIZ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SAIDA = os.path.join(RAIZ, 'tests', 'saida') + os.sep
os.makedirs(SAIDA, exist_ok=True)
from playwright.sync_api import sync_playwright
URL = 'http://127.0.0.1:8765/index.html'
falhas = []; erros = []
def check(c, m):
    print(('  ok   ' if c else '  FALHA ') + m)
    if not c: falhas.append(m)
COLOCA = "(()=>{const r=dicaDe(S.jogo); if(r.tipo!=='ok') return false; r.peca.formato=r.o; return tentarColocar(r.peca,r.px,r.py);})()"
FIM = "localStorage.setItem('shapepuzzle.tuto','{\"sel\":true,\"giro\":true,\"esp\":true,\"fim\":true}')"
def fecha_tudo(pg): pg.evaluate("document.querySelectorAll('.ov.on').forEach(o=>o.classList.remove('on'))"); pg.wait_for_timeout(100)
def nova(pg, i=0):
    fecha_tudo(pg); pg.evaluate(f"carregar({{k:'b',i:{i}}})"); pg.wait_for_timeout(200)
with sync_playwright() as pw:
    b = pw.chromium.launch()
    ctx = b.new_context(locale='pt-BR', viewport={'width': 1100, 'height': 800})
    ctx.add_init_script("try{" + FIM + "}catch(e){}")
    pg = ctx.new_page(); pg.on('pageerror', lambda e: erros.append(str(e)))
    pg.goto(URL); pg.click('#btnJogar'); pg.wait_for_timeout(400)
    nova(pg)

    print('Dica em degraus')
    check(pg.evaluate("visiveis(S.jogo).length") > 1, 'fase 1 mostra várias peças (o degrau "qual peça" faz sentido)')
    esperada = pg.evaluate("dicaDe(S.jogo).peca.uid")
    pg.click('#btnDica'); pg.wait_for_timeout(200)
    check(pg.evaluate("S.dicas") == 0, 'degrau 1 (só a peça) não conta como dica')
    check(pg.evaluate("document.querySelectorAll('#reserva .pw.dicaP').length") == 1, 'uma peça da reserva fica marcada')
    check(pg.evaluate("document.querySelector('#reserva .pw.dicaP').dataset.uid") == str(esperada), 'a marcada é a peça certa')
    check(pg.evaluate("S.sel && S.sel.uid") == esperada, 'ela já vem selecionada')
    check(pg.evaluate("document.querySelectorAll('.cell.dica').length") == 0, 'ainda não mostra o lugar')
    pg.screenshot(path=SAIDA + 'dica-degrau1.png')
    pg.click('#btnDica'); pg.wait_for_timeout(200)
    check(pg.evaluate("S.dicas") == 1, 'degrau 2 (o lugar) conta como dica')
    check(pg.evaluate("document.querySelectorAll('.cell.dica').length") >= 3, 'o lugar aparece no tabuleiro')
    check(pg.evaluate("document.querySelectorAll('#reserva .pw.dicaP').length") == 0, 'a marca da peça sai')
    pg.screenshot(path=SAIDA + 'dica-degrau2.png')
    pg.click('#btnDica'); pg.wait_for_timeout(300)
    check(pg.evaluate("document.querySelector('#ov-solucao').classList.contains('on')"), 'degrau 3: oferece a solução')
    check(pg.evaluate("S.dicas") == 1, 'oferecer a solução não aumenta a contagem')
    pg.screenshot(path=SAIDA + 'dica-degrau3.png')
    pg.click('#solFechar'); pg.wait_for_timeout(200)
    check(not pg.evaluate("document.querySelector('#ov-solucao').classList.contains('on')"), '"Continuar jogando" fecha')
    check(pg.evaluate("S.sol") is None and pg.evaluate("document.querySelectorAll('.solp').length") == 0, 'nada foi animado')

    print('Mostrar o lugar de novo')
    pg.press('body', 'h'); pg.wait_for_timeout(200)
    check(pg.evaluate("document.querySelector('#ov-solucao').classList.contains('on')"), 'tecla H também chega ao degrau 3')
    pg.click('#solLugar'); pg.wait_for_timeout(250)
    check(pg.evaluate("document.querySelectorAll('.cell.dica').length") >= 3 and pg.evaluate("S.dicas") == 1, 'volta a mostrar o lugar sem contar outra dica')

    print('Jogada nova reinicia os degraus')
    pg.evaluate(COLOCA); pg.wait_for_timeout(150)
    pg.click('#btnDica'); pg.wait_for_timeout(200)
    check(pg.evaluate("document.querySelectorAll('#reserva .pw.dicaP').length") == 1 and not pg.evaluate("document.querySelector('#ov-solucao').classList.contains('on')"), 'depois de encaixar, a dica recomeça pela peça')

    print('Solução animada')
    nova(pg)
    total = pg.evaluate("S.jogo.reserva.length"); vazias = pg.evaluate("S.n*S.n - S.jogo.mapa.size*0")  # tabuleiro vazio
    pg.evaluate("abrir('solucao')"); pg.click('#solVer'); pg.wait_for_timeout(1500)
    check(pg.evaluate("!!S.sol"), 'animação começou')
    a = pg.evaluate("document.querySelectorAll('.solp').length"); pg.wait_for_timeout(1000)
    b2 = pg.evaluate("document.querySelectorAll('.solp').length")
    check(0 < a < b2, f'as peças aparecem uma a uma ({a} → {b2} casas)')
    check('Solução' in pg.inner_text('#dica'), 'o texto de ajuda mostra o andamento')
    pg.wait_for_timeout(900 * total)
    n_sol = pg.evaluate("document.querySelectorAll('.solp').length")
    check(n_sol == vazias, f'no fim, todas as {vazias} casas estão preenchidas ({n_sol})')
    check(pg.evaluate("S.sol.i") == total, 'mostrou as ' + str(total) + ' peças')
    check('Esta é a solução' in pg.inner_text('#dica'), 'mensagem final')
    pg.screenshot(path=SAIDA + 'solucao-final.png')
    jog = pg.evaluate("S.jog")
    pg.mouse.click(550, 250); pg.wait_for_timeout(300)
    check(pg.evaluate("S.sol") is None and pg.evaluate("document.querySelectorAll('.solp').length") == 0, 'um toque encerra e limpa')
    check(pg.evaluate("S.jog") == jog and pg.evaluate("S.jogo.mapa.size") == 0, 'o toque que encerrou não encaixou nada')
    check(pg.evaluate("S.dicas") == 1, 'ver a solução conta como dica')
    pg.evaluate("S.hist=[]")

    print('Parar com o teclado e trocar de fase durante a animação')
    pg.evaluate("acaoSolucao()"); pg.wait_for_timeout(1200)
    pg.keyboard.press('a'); pg.wait_for_timeout(200)
    check(pg.evaluate("S.sol") is None, 'tecla qualquer encerra')
    pg.evaluate("acaoSolucao()"); pg.wait_for_timeout(1200)
    pg.evaluate("carregar({k:'b',i:1})"); pg.wait_for_timeout(300)
    check(pg.evaluate("S.sol") is None and pg.evaluate("document.querySelectorAll('.solp').length") == 0, 'trocar de fase limpa a animação')
    check(pg.evaluate("S.dicas") == 0 and not pg.evaluate("S.solVista"), 'a fase nova começa sem dicas')

    print('Solução parte do que já está no tabuleiro')
    nova(pg); pg.evaluate(COLOCA); pg.evaluate(COLOCA)
    ja = pg.evaluate("S.jogo.mapa.size"); resta = pg.evaluate("S.jogo.reserva.length")
    pg.evaluate("acaoSolucao()"); pg.wait_for_timeout(900 * (resta + 1))
    check(pg.evaluate("S.sol.i") == resta, f'mostra só as {resta} peças que faltam (já havia {ja})')
    pg.keyboard.press('a'); pg.wait_for_timeout(200)

    print('Com peça errada, mostra do zero')
    nova(pg)
    pg.evaluate("""(()=>{const j=S.jogo;
      for(const p of j.reserva){ for(const o of orientacoes(p.formato)){ for(let y=0;y<j.n;y++) for(let x=0;x<j.n;x++){
        if(!podeColocar(j,o,x,y)) continue; let ruim=false; o.forEach((l,a)=>l.forEach((v,c)=>{const g=j.gab[y+a][x+c]; if(v&&g&&g!==p.id) ruim=true;}));
        if(ruim){ p.formato=o; S.sel=p; tentarColocar(p,x,y); return true; } } } } return false; })()""")
    pg.wait_for_timeout(200)
    check(pg.evaluate("S.jogo.mapa.size") == 1, 'montei uma peça no lugar errado')
    pg.evaluate("acaoSolucao()"); pg.wait_for_timeout(500)
    check(pg.evaluate("!!S.sol"), 'mesmo assim a solução aparece (do zero)')
    pg.keyboard.press('a'); pg.wait_for_timeout(200)

    print('Estrelas e dica de degrau 1')
    nova(pg); pg.click('#btnDica'); pg.wait_for_timeout(150)
    n = 0
    while not pg.evaluate("S.venceu") and n < 40: pg.evaluate(COLOCA); n += 1
    pg.wait_for_selector('#ov-win.on', timeout=5000); pg.wait_for_timeout(300)
    check(pg.evaluate("S.dicas") == 0 and pg.evaluate("document.querySelectorAll('#winEstrelas svg.on').length") == 3, 'só ver a peça mantém as 3 estrelas')
    nova(pg); pg.evaluate("acaoSolucao()"); pg.wait_for_timeout(300); pg.keyboard.press('a'); pg.wait_for_timeout(200)
    n = 0
    while not pg.evaluate("S.venceu") and n < 40: pg.evaluate(COLOCA); n += 1
    pg.wait_for_selector('#ov-win.on', timeout=5000); pg.wait_for_timeout(300)
    check(pg.evaluate("document.querySelectorAll('#winEstrelas svg.on').length") == 1 and 'recorde' in pg.inner_text('#winBadge'), 'depois de ver a solução: 1 estrela e sem recorde')

    print('Símbolos de daltônico na solução')
    fecha_tudo(pg); nova(pg)
    pg.evaluate("salvarA11y('dalt', true)"); pg.evaluate("acaoSolucao()"); pg.wait_for_timeout(1200)
    bg = pg.evaluate("(()=>{const e=document.querySelector('.solp'); return e? getComputedStyle(e,'::after').backgroundImage : ''})()")
    check('url' in bg, 'peças da solução têm símbolo no modo daltônico')
    pg.keyboard.press('a'); pg.evaluate("salvarA11y('dalt', false)")

    print('Em campeonato não há dica nem solução')
    pg.evaluate("carregar({k:'b',i:0})"); pg.wait_for_timeout(150)
    pg.evaluate("S.cur.k='x'"); pg.evaluate("acaoSolucao()")
    check(pg.evaluate("S.sol") is None, 'acaoSolucao não roda em campeonato')
    pg.evaluate("S.cur.k='b'")

    print('QR code')
    fecha_tudo(pg)
    pg.evaluate("compartilhar('Shape Puzzle','Joga comigo!', urlBase())"); pg.wait_for_timeout(300)
    check(pg.is_visible('#shQR') and not pg.is_visible('#shQRBox'), 'botão aparece e o QR começa escondido')
    pg.click('#shQR'); pg.wait_for_timeout(300)
    check(pg.is_visible('#shQRCanvas') and pg.evaluate("document.querySelector('#shQR').getAttribute('aria-expanded')") == 'true', 'QR aparece')
    check('Esconder' in pg.inner_text('#shQR'), 'botão vira "Esconder QR code"')
    pg.locator('#shQRCanvas').screenshot(path=SAIDA + 'qr.png')
    import cv2
    img = cv2.imread(SAIDA + 'qr.png'); img = cv2.resize(img, None, fx=3, fy=3, interpolation=cv2.INTER_NEAREST)
    txt, _, _ = cv2.QRCodeDetector().detectAndDecode(img)
    esperado = pg.evaluate("urlBase()")
    check(txt == esperado, f'o QR lido pela câmera (OpenCV) abre o link do jogo: {txt!r}')
    pg.screenshot(path=SAIDA + 'qr-painel.png')
    pg.click('#shQR'); pg.wait_for_timeout(150)
    check(not pg.is_visible('#shQRBox'), 'esconde de novo')
    pg.click('#shQR'); pg.click('[data-close=share]'); pg.wait_for_timeout(200)
    pg.evaluate("compartilhar('Shape Puzzle','x', urlBase())"); pg.wait_for_timeout(200)
    check(not pg.is_visible('#shQRBox'), 'ao abrir de novo, o QR volta escondido')
    # link de fase compartilhada (mais longo)
    fecha_tudo(pg)
    longo = pg.evaluate("urlFase(BUILTIN[0].text, 'Minha fase')")
    pg.evaluate("compartilhar('Shape Puzzle','Tente!', urlFase(BUILTIN[0].text, 'Minha fase'))"); pg.click('#shQR'); pg.wait_for_timeout(300)
    pg.locator('#shQRCanvas').screenshot(path=SAIDA + 'qr-fase.png')
    img = cv2.imread(SAIDA + 'qr-fase.png'); img = cv2.resize(img, None, fx=3, fy=3, interpolation=cv2.INTER_NEAREST)
    txt, _, _ = cv2.QRCodeDetector().detectAndDecode(img)
    check(txt == longo, f'QR de uma fase compartilhada também lê certo ({len(longo)} caracteres)')

    print('Celular: painel de compartilhar cabe na tela')
    ctx2 = b.new_context(locale='pt-BR', viewport={'width': 360, 'height': 640}, has_touch=True, is_mobile=True)
    ctx2.add_init_script("try{" + FIM + "}catch(e){}")
    p2 = ctx2.new_page(); p2.on('pageerror', lambda e: erros.append(str(e)))
    p2.goto(URL); p2.click('#btnJogar'); p2.wait_for_timeout(400)
    p2.evaluate("compartilhar('Shape Puzzle','Joga comigo!', urlBase())"); p2.click('#shQR'); p2.wait_for_timeout(300)
    r = p2.evaluate("(()=>{const c=document.querySelector('#shQRCanvas').getBoundingClientRect(); return [c.width, c.left, c.right, innerWidth]})()")
    check(r[0] >= 200 and r[1] >= 0 and r[2] <= r[3], f'QR com tamanho bom e dentro da tela ({round(r[0])} px)')
    p2.evaluate("document.querySelector('#ov-share .card').scrollTop=9999"); p2.screenshot(path=SAIDA + 'qr-celular.png')
    p2.evaluate("fechar('share')"); p2.wait_for_timeout(100)
    print('Celular: dica degrau 1 e solução')
    p2.evaluate("carregar({k:'b',i:0})"); p2.wait_for_timeout(200)
    p2.tap('#btnDica'); p2.wait_for_timeout(250)
    check(p2.evaluate("document.querySelectorAll('#reserva .pw.dicaP').length") == 1, 'toque na dica marca a peça')
    p2.screenshot(path=SAIDA + 'dica-celular.png')
    p2.evaluate("acaoSolucao()"); p2.wait_for_timeout(2500)
    p2.screenshot(path=SAIDA + 'solucao-celular.png')
    p2.touchscreen.tap(180, 200); p2.wait_for_timeout(300)
    check(p2.evaluate("S.sol") is None, 'toque no celular encerra a solução')
    check(p2.evaluate("document.documentElement.scrollHeight <= innerHeight + 1"), 'sem rolagem na tela do jogo')
    b.close()
print('erros de página:', erros)
if erros: falhas.append('erros de página')
print('TUDO OK' if not falhas else 'FALHAS: ' + str(falhas)); sys.exit(1 if falhas else 0)
