const t=require('targaryen'),fs=require('fs');
const rules=JSON.parse(fs.readFileSync(require('path').join(__dirname,'..','firebase-rules.json'),'utf8'));
let ok=true;const chk=(c,m)=>{console.log((c?'  ok   ':'  FALHA ')+m);if(!c)ok=false;};
const NOW=1700000000000;
const fase={nome:'Fase 1',text:'GABARITO:\n0\nPECAS_CUSTOM:\n1:0-0;\n'};
const camp=(o={})=>({nome:'Copa',org:'Ana',max:10,modo:'melhor',fim:0,criado:NOW,uid:'dono',fases:[fase,fase],...o});
const db=(data={})=>t.database(rules,data).with({now:NOW});
const dono={uid:'dono'},outro={uid:'outro'};
const w=(d,a,p,v)=>d.as(a).write(p,v,{now:NOW}).allowed;
const r=(d,a,p)=>d.as(a).read(p,{now:NOW}).allowed;
console.log('Criar');
chk(w(db(),dono,'/c/ABC123',camp()),'organizador logado cria campeonato');
chk(!w(db(),null,'/c/ABC123',camp()),'sem login não cria');
chk(!w(db(),outro,'/c/ABC123',camp()),'não cria em nome de outro uid');
chk(!w(db(),dono,'/c/ABC12',camp()),'código com tamanho errado recusado');
for(const [k,v] of [['max',1],['max',201],['modo','x'],['nome','a'],['fim',-1],['fases',Array(0)]]) chk(!w(db(),dono,'/c/ABC123',camp({[k]:v})),`valor inválido recusado: ${k}=${JSON.stringify(v)}`);
chk(!w(db(),dono,'/c/ABC123',{...camp(),extra:1}),'campo extra recusado');
chk(!w(db(),dono,'/c/ABC123',camp({fases:[{nome:'x',text:'y'.repeat(2001)}]})),'fase gigante recusada');
console.log('Ler');
const base={c:{ABC123:camp()}};
chk(r(db(base),null,'/c/ABC123'),'qualquer um lê um campeonato pelo código');
chk(!r(db(base),null,'/c'),'ninguém lista todos os campeonatos');
chk(!r(db(base),dono,'/'),'nem o dono lê a raiz');
console.log('Excluir / editar');
chk(w(db(base),dono,'/c/ABC123',null),'dono exclui o campeonato');
chk(!w(db(base),outro,'/c/ABC123',null),'outro uid não exclui');
chk(!w(db(base),null,'/c/ABC123',null),'sem login não exclui');
chk(w(db(base),dono,'/c/ABC123',camp({nome:'Novo nome',max:20})),'dono edita enquanto ninguém entrou');
chk(!w(db(base),outro,'/c/ABC123',camp({nome:'Invadido',uid:'outro'})),'outro não edita');
chk(!w(db(base),dono,'/c/ABC123',camp({uid:'outro'})),'dono não passa o campeonato para outro uid');
chk(!w(db(base),dono,'/c/ABC123',camp({criado:NOW+5})),'data de criação não muda');
const comGente={...base,p:{ABC123:{beto:{n:'Beto',ts:NOW}}}};
chk(!w(db(comGente),dono,'/c/ABC123',camp({nome:'Mudou'})),'depois que alguém entra, o dono não edita mais');
chk(w(db(comGente),dono,'/c/ABC123',null),'mas o dono ainda exclui');
chk(w(db(comGente),dono,'/p/ABC123',null),'dono apaga a lista de participantes');
chk(!w(db(comGente),outro,'/p/ABC123',null),'outro não apaga participantes');
chk(!w(db(comGente),null,'/p/ABC123/beto',null),'ninguém apaga um participante');
console.log('Participantes');
chk(w(db(base),null,'/p/ABC123/ana',{n:'Ana',ts:NOW}),'entrar só com nome (sem login)');
chk(!w(db(),null,'/p/ZZZZZZ/ana',{n:'Ana',ts:NOW}),'não entra em campeonato que não existe');
chk(!w(db(comGente),null,'/p/ABC123/beto',{n:'Outro',ts:NOW}),'não reescreve um jogador existente');
chk(!w(db(base),null,'/p/ABC123/a',{n:'Ana',ts:NOW}),'chave curta demais recusada');
chk(!w(db(base),null,'/p/ABC123/ana',{n:'Ana',ts:NOW,x:1}),'campo extra recusado');
chk(r(db(comGente),null,'/p/ABC123'),'ranking é legível por quem tem o código');
console.log('Resultados');
chk(w(db(comGente),null,'/p/ABC123/beto/f/0',{t:5000,j:8}),'jogador grava resultado');
chk(!w(db(base),null,'/p/ABC123/fantasma/f/0',{t:5000,j:8}),'sem entrar antes, não grava');
chk(!w(db(comGente),null,'/p/ABC123/beto/f/0',{t:100,j:8}),'tempo impossível (<0,5 s) recusado');
chk(!w(db(comGente),null,'/p/ABC123/beto/f/0',{t:5000,j:0}),'jogadas inválidas recusadas');
chk(!w(db(comGente),null,'/p/ABC123/beto/f/12',{t:5000,j:8}),'fase fora de 0-9 recusada');
const feito={...comGente,p:{ABC123:{beto:{n:'Beto',ts:NOW,f:{0:{t:5000,j:8}}}}}};
chk(w(db(feito),null,'/p/ABC123/beto/f/0',{t:4000,j:8}),'modo melhor: tempo menor substitui');
chk(!w(db(feito),null,'/p/ABC123/beto/f/0',{t:6000,j:8}),'modo melhor: tempo maior não substitui');
const prim={c:{ABC123:camp({modo:'primeira'})},p:feito.p};
chk(!w(db(prim),null,'/p/ABC123/beto/f/0',{t:4000,j:8}),'modo primeira: não substitui nem melhorando');
chk(w(db(prim),null,'/p/ABC123/beto/f/1',{t:4000,j:8}),'modo primeira: fase nova entra');
const prazo={c:{ABC123:camp({fim:NOW-1000})},p:comGente.p};
chk(!w(db(prazo),null,'/p/ABC123/beto/f/0',{t:5000,j:8}),'depois do prazo não grava');
const noPrazo={c:{ABC123:camp({fim:NOW+100000})},p:comGente.p};
chk(w(db(noPrazo),null,'/p/ABC123/beto/f/0',{t:5000,j:8}),'dentro do prazo grava');
chk(!w(db(base),null,'/p/ABC123/golpe',{n:'Golpe',ts:NOW,f:{0:{t:5000,j:8}}}),'não dá para entrar já com resultados prontos');
chk(!w(db(prazo),null,'/p/ABC123/novo',{n:'Novo',ts:NOW,f:{0:{t:5000,j:8}}}),'nem depois do prazo, criando o jogador com resultado');
console.log('Raiz');
chk(!w(db(),dono,'/x',1),'nada fora de c e p');
chk(!w(db(),dono,'/',{}),'não dá para apagar/escrever a raiz');
console.log(ok?'REGRAS: TUDO OK':'REGRAS COM FALHAS');process.exit(ok?0:1);
