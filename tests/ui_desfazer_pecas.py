import os, sys
RAIZ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SAIDA = os.path.join(RAIZ, 'tests', 'saida') + os.sep
os.makedirs(SAIDA, exist_ok=True)
from playwright.sync_api import sync_playwright
URL = 'http://127.0.0.1:8765/index.html'
falhas = []; erros = []
def check(c, m):
    print(('  ok   ' if c else '  FALHA ') + m)
    if not c: falhas.append(m)
COLOCA = "(()=>{const r=dicaDe(S.jogo); if(r.tipo!=='ok') return false; r.peca.formato=r.o; return tentarColocar(r.peca,r.px,r.py);})()"
FIM = "localStorage.setItem('shapepuzzle.tuto','{\"sel\":true,\"giro\":true,\"esp\":true,\"fim\":true}')"
with sync_playwright() as pw:
    b = pw.chromium.launch()
    ctx = b.new_context(locale='pt-BR', viewport={'width': 1280, 'height': 720}); ctx.add_init_script("try{" + FIM + "}catch(e){}")
    pg = ctx.new_page(); pg.on('pageerror', lambda e: erros.append(str(e)))
    pg.goto(URL); pg.click('#btnJogar'); pg.wait_for_timeout(400)
    pg.evaluate("carregar({k:'b',i:0})"); pg.wait_for_timeout(200)
    print('Desfazer')
    check(pg.is_disabled('#btnDesfazer'), 'começa desativado (nada a desfazer)')
    check(pg.evaluate(COLOCA) is True and pg.evaluate(COLOCA) is True, 'duas peças colocadas')
    check(not pg.is_disabled('#btnDesfazer'), 'ativa depois de colocar peças')
    tot = pg.evaluate("S.jogo.total"); jog = pg.evaluate("S.jog")
    check(pg.evaluate("S.jogo.mapa.size") == 2, 'tabuleiro com 2 peças')
    pg.click('#btnDesfazer'); pg.wait_for_timeout(150)
    check(pg.evaluate("S.jogo.mapa.size") == 1, 'clicar em Desfazer tira a última peça')
    check(pg.evaluate("S.jogo.reserva.length") == tot - 1, 'a peça voltou para a reserva')
    check(pg.evaluate("!!S.sel && S.jogo.reserva.includes(S.sel)"), 'a peça devolvida fica selecionada')
    check(pg.evaluate("S.jog") == jog, 'não altera a contagem de movimentos')
    pg.keyboard.press('z'); pg.wait_for_timeout(150)
    check(pg.evaluate("S.jogo.mapa.size") == 0, 'tecla Z também desfaz')
    check(pg.is_disabled('#btnDesfazer'), 'desativa quando não há mais o que desfazer')
    pg.keyboard.press('z'); pg.wait_for_timeout(100)
    check(pg.evaluate("S.jogo.mapa.size") == 0, 'Z sem nada a desfazer não quebra')
    print('Desfazer depois de tirar uma peça à mão')
    pg.evaluate(COLOCA); pg.evaluate(COLOCA)
    pg.evaluate("(()=>{const idu=S.hist[0]; for(let y=0;y<S.n;y++)for(let x=0;x<S.n;x++) if(S.jogo.grade[y][x]===idu){const p=remover(S.jogo,x,y); devolver(p); renderBoard(); renderReserva(); return;}})()")
    check(pg.evaluate("S.jogo.mapa.size") == 1, 'uma peça tirada manualmente')
    pg.click('#btnDesfazer'); pg.wait_for_timeout(100)
    check(pg.evaluate("S.jogo.mapa.size") == 0, 'desfazer ignora peças já tiradas e remove a que sobrou')
    pg.click('#btnReset'); pg.wait_for_timeout(200)
    check(pg.evaluate("S.hist.length") == 0 and pg.is_disabled('#btnDesfazer'), 'reiniciar limpa o histórico')
    print('Desfazer ao vencer')
    n = 0
    while not pg.evaluate("S.venceu") and n < 30:
        pg.evaluate(COLOCA); n += 1
    check(pg.evaluate("S.venceu"), 'fase concluída pelas dicas')
    check(pg.is_disabled('#btnDesfazer'), 'Desfazer desativado na vitória')
    pg.evaluate("document.querySelectorAll('.ov.on').forEach(o=>o.classList.remove('on'))")
    pg.keyboard.press('z'); pg.wait_for_timeout(100)
    check(pg.evaluate("S.venceu && S.jogo.mapa.size>0"), 'Z não desfaz depois de vencer')

    print('Peças por vez')
    pg.evaluate("carregar({k:'b',i:0})"); pg.wait_for_timeout(200)
    check(pg.evaluate("visiveis(S.jogo).length") == 6, 'padrão automático: 6 peças na fase 1')
    pg.click('#btnMenu'); pg.wait_for_timeout(200)
    check(pg.evaluate("document.querySelector('#selPecas').value") == 'auto', 'menu mostra Automático')
    pg.select_option('#selPecas', '3'); pg.wait_for_timeout(200)
    pg.evaluate("document.querySelectorAll('.ov.on').forEach(o=>o.classList.remove('on'))"); pg.wait_for_timeout(200)
    check(pg.evaluate("visiveis(S.jogo).length") == 3 and pg.locator('#reserva .pw').count() == 3, 'escolher 3 passa a mostrar 3 peças na hora')
    pg.evaluate(COLOCA)
    pg.click('#btnMenu'); pg.wait_for_timeout(200); pg.select_option('#selPecas', '2'); pg.wait_for_timeout(200); pg.evaluate("document.querySelectorAll('.ov.on').forEach(o=>o.classList.remove('on'))")
    check(pg.evaluate("S.jogo.mapa.size") == 1 and pg.locator('#reserva .pw').count() == 2, 'trocar no meio da fase mantém as peças já encaixadas')
    pg.evaluate("carregar({k:'b',i:12})"); pg.wait_for_timeout(200)
    check(pg.evaluate("visiveis(S.jogo).length") == 2, 'a escolha vale para outras fases (fase 13)')
    pg.reload(); pg.click('#btnJogar'); pg.wait_for_timeout(400)
    pg.evaluate("carregar({k:'b',i:20})"); pg.wait_for_timeout(200)
    check(pg.evaluate("pecasPref") == 2 and pg.evaluate("visiveis(S.jogo).length") == 2, 'a escolha fica salva no aparelho')
    check(pg.evaluate("filaPadraoDe({k:'x'})") == 4, 'campeonatos ignoram a escolha (sempre 4)')
    pg.click('#btnMenu'); pg.wait_for_timeout(200); pg.select_option('#selPecas', '99'); pg.wait_for_timeout(200); pg.evaluate("document.querySelectorAll('.ov.on').forEach(o=>o.classList.remove('on'))")
    check(pg.evaluate("visiveis(S.jogo).length") == pg.evaluate("S.jogo.total") and pg.evaluate("S.jogo.fila") == 0, '"Todas" mostra todas as peças')
    check(pg.evaluate("document.documentElement.scrollHeight") <= 720, 'sem rolagem com todas as peças')
    pg.click('#btnMenu'); pg.wait_for_timeout(200); pg.select_option('#selPecas', 'auto'); pg.wait_for_timeout(200); pg.evaluate("document.querySelectorAll('.ov.on').forEach(o=>o.classList.remove('on'))")
    pg.evaluate("carregar({k:'b',i:0})"); pg.wait_for_timeout(200)
    check(pg.evaluate("visiveis(S.jogo).length") == 6, 'voltar ao automático restaura 6 na fase 1')
    fixa = pg.evaluate("(()=>{const i=BUILTIN.findIndex(f=>parseFase(f.text).fila); return i;})()")
    if fixa >= 0:
        pg.click('#btnMenu'); pg.wait_for_timeout(200); pg.select_option('#selPecas', '6'); pg.wait_for_timeout(200); pg.evaluate("document.querySelectorAll('.ov.on').forEach(o=>o.classList.remove('on'))")
        pg.evaluate(f"carregar({{k:'b',i:{fixa}}})"); pg.wait_for_timeout(200)
        check(pg.evaluate("S.jogo.filaFixa") is True and pg.evaluate("S.jogo.fila") == pg.evaluate(f"parseFase(BUILTIN[{fixa}].text).fila"), 'fase com FILA própria mantém a dela')
    else:
        print('   (nenhuma fase embutida com FILA própria)')
    ctx.close()

    print('Telas pequenas (celular)')
    for w, h in [(320, 568), (360, 640), (390, 844)]:
        c2 = b.new_context(locale='pt-BR', viewport={'width': w, 'height': h}, has_touch=True, is_mobile=True); c2.add_init_script("try{" + FIM + "}catch(e){}")
        p2 = c2.new_page(); p2.on('pageerror', lambda e: erros.append(str(e)))
        p2.goto(URL); p2.click('#btnJogar'); p2.wait_for_timeout(400)
        for i in (0, 14, 35):
            p2.evaluate("carregar({k:'b',i:%d})" % i); p2.wait_for_timeout(200)
            check(p2.evaluate("document.documentElement.scrollHeight") <= h and p2.evaluate("document.documentElement.scrollWidth") <= w, f'{w}x{h} fase {i+1}: sem rolagem')
        hd = p2.evaluate("(()=>{const t=document.querySelector('header.top');return [t.scrollWidth,t.clientWidth]})()")
        check(hd[0] <= hd[1] + 1, f'{w}x{h}: cabeçalho cabe com 5 botões ({hd})')
        bx = p2.locator('#btnMusica').bounding_box()
        check(bx['x'] + bx['width'] <= w, f'{w}x{h}: botão de música dentro da tela')
        if w == 320: p2.screenshot(path=SAIDA + 'desfazer-320.png')
        c2.close()
    b.close()
print('erros de página:', erros)
if erros: falhas.append('erros de página')
print('\nFALHAS:' if falhas else '\nTUDO OK', falhas if falhas else '')
sys.exit(1 if falhas else 0)
