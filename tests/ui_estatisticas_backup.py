# Estatísticas pessoais e backup do progresso (salvar, copiar, baixar, restaurar juntando ou substituindo).
import os, sys, re, json
RAIZ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SAIDA = os.path.join(RAIZ, 'tests', 'saida') + os.sep
os.makedirs(SAIDA, exist_ok=True)
from playwright.sync_api import sync_playwright
URL = 'http://127.0.0.1:8765/index.html'
falhas = []; erros = []
def check(c, m):
    print(('  ok   ' if c else '  FALHA ') + m)
    if not c: falhas.append(m)
COLOCA = "(()=>{const r=dicaDe(S.jogo); if(r.tipo!=='ok') return false; r.peca.formato=r.o; return tentarColocar(r.peca,r.px,r.py);})()"
FIM = "localStorage.setItem('shapepuzzle.tuto','{\"sel\":true,\"giro\":true,\"esp\":true,\"fim\":true}')"
def fecha_tudo(pg): pg.evaluate("document.querySelectorAll('.ov.on').forEach(o=>o.classList.remove('on'))"); pg.wait_for_timeout(100)
def vencer(pg):
    n = 0
    while not pg.evaluate("S.venceu") and n < 60: pg.evaluate(COLOCA); n += 1
    pg.wait_for_selector('#ov-win.on', timeout=8000); pg.wait_for_timeout(250); fecha_tudo(pg)
def novo(b, locale='pt-BR', w=390, h=844, extra=''):
    ctx = b.new_context(locale=locale, viewport={'width': w, 'height': h}, has_touch=True, is_mobile=True, accept_downloads=True)
    ctx.add_init_script("try{" + FIM + "}catch(e){}" + extra)
    pg = ctx.new_page(); pg.on('pageerror', lambda e: erros.append(str(e)))
    pg.goto(URL); pg.click('#btnJogar'); pg.wait_for_timeout(400)
    return ctx, pg
def ls(pg, k): return pg.evaluate(f"JSON.parse(localStorage.getItem('shapepuzzle.{k}'))")
def valores(pg): return pg.evaluate("[...document.querySelectorAll('#estCorpo .sv')].map(e=>[e.firstChild.textContent, e.lastChild.textContent])")
