    check(p2.evaluate("document.documentElement.dataset.tema") == 'poente' and p2.evaluate("a11y.dalt") is True, 'tema e acessibilidade voltaram')
    check(p2.evaluate("Object.keys(recs).length") >= 1 and p2.evaluate("Object.keys(estrelasFase).length") == 2, 'recordes e estrelas voltaram')
