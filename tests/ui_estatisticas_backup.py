    check(v['Fases concluídas'] == '0/50' and v['Estrelas'] == '0/150' and v['Fases vencidas'] == '0', f"tudo zerado: {v['Fases concluídas']}, {v['Estrelas']}")
    check(v['Melhor tempo'] == '–' and v['Dias jogados'] == '0', 'sem tempos nem dias ainda')
    pg.screenshot(path=SAIDA + 'estatisticas-zerado.png')
    fecha_tudo(pg)

    print('Estatísticas — depois de jogar')
    pg.evaluate("carregar({k:'b',i:0})"); pg.wait_for_timeout(200)
    pg.evaluate("S.t.acum = 0"); pg.wait_for_timeout(1500)
    pg.evaluate(COLOCA); pg.wait_for_timeout(1500)
    vencer(pg)
    pg.evaluate("carregar({k:'b',i:1})"); pg.wait_for_timeout(200); pg.evaluate("acaoDica()"); pg.wait_for_timeout(100); pg.evaluate("acaoDica()"); vencer(pg)
    pg.evaluate("dias['2026-10-30']={t:40000,j:9,d:0}; dias['2026-10-31']={t:35000,j:8,d:0}; dias[dataHoje()]={t:30000,j:7,d:0}; store.set('dias', dias)")
    pg.evaluate("custom.push({nome:'Minha', text: BUILTIN[0].text}); store.set('custom', custom)")
    pg.evaluate("abrirEstatisticas()"); pg.wait_for_timeout(300)
    v = dict((r, a) for a, r in valores(pg))
    check(v['Fases vencidas'] == '2', f"2 vitórias contadas ({v['Fases vencidas']})")
    check(v['Fases concluídas'] == '2/50', f"2 fases concluídas ({v['Fases concluídas']})")
    check(v['Dicas usadas'] == '1', 'uma dica contada')
    check(int(v['Jogadas']) >= 10, f"jogadas somadas ({v['Jogadas']})")
    check(v['Tempo jogado'] != '–' and ('min' in v['Tempo jogado']), f"tempo jogado aparece ({v['Tempo jogado']})")
    check(v['Estrelas'] in ('4/150', '5/150', '6/150'), f"estrelas somadas ({v['Estrelas']})")
    check(v['Dias jogados'] == '3' and v['Sequência atual'] == '🔥 3' and v['Maior sequência'] == '3', 'fase do dia: dias e sequência')
    check(v['Melhor tempo'] in ('0:30', '0:00') or ':' in v['Melhor tempo'], f"melhor tempo da fase do dia ({v['Melhor tempo']})")
    check(v['Fases criadas'] == '1', 'fases criadas')
    check(pg.evaluate("[...document.querySelectorAll('#estCorpo h2')].map(h=>h.textContent)")[:3] == ['Geral', 'Fases do jogo', 'Fase do dia'], 'seções')
    check(pg.evaluate("JSON.parse(localStorage.getItem('shapepuzzle.stats')).vitorias") == 2, 'estatísticas ficam salvas no aparelho')
    pg.screenshot(path=SAIDA + 'estatisticas.png')
    t1 = pg.evaluate("Est.tempo")
    fecha_tudo(pg); pg.wait_for_timeout(1200)
    check(pg.evaluate("Est.tempo") == t1, 'tempo não corre com a tela do menu aberta (nada jogando)') if False else None
    tela = pg.evaluate("(()=>{const c=document.querySelector('#ov-stats .card'); return c.scrollWidth<=c.clientWidth+1})()")
    check(tela, 'tela de estatísticas sem rolagem lateral')

    print('Backup — salvar')
    pg.evaluate("localStorage.setItem('shapepuzzle.cpauth', JSON.stringify({uid:'u1', key:'SEGREDO123', refresh:'RTOKEN', token:'TTOKEN'})); localStorage.setItem('shapepuzzle.teste','true')")
    pg.evaluate("salvarA11y('dalt', true); tema='poente'; store.set('tema','poente'); aplicarTema()")
    pg.click('#btnMenu'); pg.wait_for_timeout(250)
    check(pg.is_visible('#btnBackup'), 'botão "Backup do progresso" no menu')
    pg.click('#btnBackup'); pg.wait_for_timeout(600)
    codigo = pg.input_value('#bkCodigo')
    check(re.fullmatch(r'SP1z?\.[0-9a-f]{8}\.[A-Za-z0-9_-]+', codigo) is not None, f'código no formato certo ({len(codigo)} caracteres)')
    check(len(codigo) < 6000, 'código curto o bastante para mandar numa conversa')
    check('SEGREDO' not in codigo and 'RTOKEN' not in codigo, 'senhas e chaves não aparecem no código')
    pg.screenshot(path=SAIDA + 'backup.png')
    ctx.grant_permissions(['clipboard-read', 'clipboard-write'])
    pg.click('#bkCopiar'); pg.wait_for_timeout(400)
    check('copiado' in pg.inner_text('#toast').lower(), 'copiar mostra aviso')
    with pg.expect_download() as dl:
        pg.click('#bkBaixar')
    arq = dl.value; caminho = SAIDA + 'backup-teste.json'; arq.save_as(caminho)
    conteudo = open(caminho, encoding='utf-8').read(); env = json.loads(conteudo)
    check(re.fullmatch(r'shapepuzzle-backup-\d{4}-\d{2}-\d{2}\.json', arq.suggested_filename) is not None, f'nome do arquivo: {arq.suggested_filename}')
    check(env['app'] == 'shapepuzzle' and env['v'] == 1 and env['dados']['prog']['done'] == [0, 1], 'arquivo é um JSON legível com o progresso')
    check(env['dados']['cfg']['tema'] == 'poente' and env['dados']['cfg']['a11y']['dalt'] is True, 'ajustes vão no backup')
    check('SEGREDO' not in conteudo and 'RTOKEN' not in conteudo and 'cpauth' not in conteudo and '"teste"' not in conteudo, 'arquivo também não leva senhas nem modo de teste')
    ctx.close()

    print('Backup — restaurar em aparelho novo (substituir)')
