    p2.fill('#bkCola', codigo[:40]); p2.click('#bkConferir'); p2.wait_for_timeout(300)
    check('incompleto' in p2.inner_text('#bkAviso') and p2.is_hidden('#bkResumo'), 'código cortado é recusado com mensagem')
    p2.fill('#bkCola', codigo[:-3] + 'AAA'); p2.click('#bkConferir'); p2.wait_for_timeout(300)
